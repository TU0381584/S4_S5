#!/usr/bin/env python3
"""Writes DATA_MANIFEST.md from data.json, so every number in it is read, not typed. Run after data.py."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, "data.json")))
OLD = "experiments/plots/paper5_fig_capability.py"
NAME = {"axiom2": "AXIOM", "mappo_tuned": "MAPPO", "single_agent_dqn": "DQN-SA", "independent_dqn": "DQN-I",
        "rule_static": "Static rule", "rule_local": "Tuned rule", "axiom2_hex": "AXIOM, hex only"}
R = "experiments/results/"


def ci(v):
    return f"{v['mean']:.3f} [{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}]"


def main():
    L = ["# Data manifest, Fig. 10 variants", "",
         "Generated by make_manifest.py from data.json, which data.py computes from the stored results. Paths are relative to "
         "the repository root. CIs are 95% percentile bootstraps of the mean over seeds (scipy.stats.bootstrap, 10,000 "
         "resamples, default_rng(0)); they can differ in the last digit from the paper's CIs, which use the verifier's own "
         "bootstrap. Per-seed values for every row marked yes are stored in data.json under per_seed.", "",
         "| Value | Controller | Mean [95% CI] | N | Source file(s) | Field | Per-seed | HARDCODED |",
         "|---|---|---|---|---|---|---|---|"]
    for a, v in D["sla37"].items():
        L.append(f"| Priority-slice compliance at 37 gNBs, Env A (%) | {NAME[a]} | {ci(v)} | {v['n']} | {R}{v['source']} | "
                 "eval omega_log: mean of URLLC and eMBB SLA flags (m66_verify.prio) | yes | no |")
    for a, v in D["delay37"].items():
        L.append(f"| URLLC backlog delay at 37 gNBs, hex (control periods) | {NAME[a]} | {ci(v)} | {v['n']} | {R}{v['source']} | "
                 "kpi.urllc.delay_steps = mean backlog PRBs / mean served PRBs per control period (M77 recorder) | yes | no |")
    for a, v in D["params"].items():
        L.append(f"| Parameters at execution | {NAME[a]} | 3: {v['3']:,}; 7: {v['7']:,}; 19: {v['19']:,}; 37: {v['37']:,} | count, no seeds | "
                 f"{R}m64/complexity.json, {R}m73/complexity_n37.json | [n][arm].params_execution | n/a | no |")
    for a, v in D["transfer37"].items():
        bl = ", ".join(f"{k} {x:.2f}" for k, x in v["by_layout"].items())
        L.append(f"| Compliance at 37 gNBs of the 7-gNB checkpoint (M92), pooled 3 layouts (%) | {NAME[a]} | {ci(v)}; by layout {bl} | {v['n']} | "
                 f"{R}m92/A_*_n37/{a}_transfer | eval omega_log, prio | yes | no |")
    for a, v in D["compliance7"].items():
        L.append(f"| Compliance at 7 gNBs, trained at 7 (%) | {NAME[a]} | {ci(v)} | {v['n']} | {R}m65_scaling/n7_*/{a} | eval omega_log, prio | yes | no |")
    for a, v in D["past19"].items():
        bl = ", ".join(f"{k[5:]} {x:+.2f}" for k, x in v["by_load"].items())
        L.append(f"| Reward per step minus tuned rule's, Env B 19 gNBs, mean of 110-120% load | {NAME[a]} | {ci(v)}; by load {bl} | {v['n']} | "
                 f"{R}{'m76/b1_shift_n19' if a == 'rule_static' else 'm96/B_shift/n19_hex'}/load_1.1x | eval omega_log reward, paired by seed | yes | no |")
    for a, v in D["steady19"].items():
        L.append(f"| Reward per step minus tuned rule's, Env B 19 gNBs, nominal load | {NAME[a]} | {ci(v)} | {v['n']} | "
                 f"{R}{'m76/b1_shift_n19' if a == 'rule_static' else 'm96/B_shift/n19_hex'}/nominal | eval omega_log reward | yes | no |")
    for L_, v in D["over_tuned_rule_m76"].items():
        L.append(f"| AXIOM minus carried tuned rule, Env B 19 gNBs, {L_[5:]} load (paper's +6.23/+7.55/+8.67) | AXIOM | {v['diff']:.3f}, wins {v['wins']}/{v['n']}, p {v['p']:.2g} | {v['n']} | "
                 f"{R}m76/b1_shift_n19/{L_} | reward, paired Wilcoxon | yes | no |")
    for a, v in D["past_wins_m96"].items():
        L.append(f"| Tests won against the tuned rule past its load, 3/7/19 gNBs x 110/115/120%, Holm | {NAME[a]} | {v['wins']} of {v['tests']} | 15 or 25 per test | "
                 f"{R}m96/B_shift/{{n3,n7_ring,n19_hex}} | reward, paired Wilcoxon, Holm per controller | yes | no |")
    for a, v in D["rewardA37"].items():
        L.append(f"| Reward per step, Env A 37 gNBs hex, nominal | {NAME[a]} | {ci(v)} | {v['n']} | {R}{v['source']} | eval omega_log reward | yes | no |")
    f = D["fed_cost"]
    L.append(f"| Federated training cost, centralised minus FedAvg reward per step, Env A 3 gNBs (paper's +0.491) | AXIOM | {ci(f)}, Wilcoxon p {f['p_wilcoxon']:.2f} | {f['n']} | "
             f"{R}m65_reviewer, m65_m3, m66_fresh/A_n3, m66b_fresh/m3_s* | reward, paired by seed | yes | no |")
    for k, v in D["over_mappo_pct"].items():
        L.append(f"| AXIOM reward over MAPPO, Env B {k} gNBs (%) | AXIOM | {v['pct']:.2f} [{v['ci95'][0]:.2f}, {v['ci95'][1]:.2f}] | {v['n']} | {R}{v['source']} | "
                 "ratio of mean rewards, paired bootstrap | yes | no |")
    L.append(f"| Compliance lead over best learned baseline at 37 gNBs (pp) | AXIOM | {D['lead37']['points']:.2f} over {NAME[D['lead37']['over']]} | derived | sla37 rows | difference of means | yes | no |")
    L.append(f"| URLLC delay ratio, baseline / AXIOM | learned | " + ", ".join(f"{NAME[a]} {r:.1f}" for a, r in D["delay_ratio"].items()) + " | derived | delay37 rows | ratio of means | yes | no |")
    L.append(f"| Parameter ratio DQN-I / AXIOM at 37 gNBs | AXIOM | {D['params_ratio_dqni']:.1f} | derived | params rows | ratio | n/a | no |")
    if D.get("tuned_rule_A37"):
        L.append(f"| Thresholds of the tuned local rule, Env A 37 gNBs (M97) | Tuned rule | {D['tuned_rule_A37']} | 30 training streams | "
                 f"{R}m97/A_n37_hex/rule_local_selection.json | selected | n/a | no |")
    L += ["", "## Entries that are not measurements", "",
          "| Entry | Where used | Basis | HARDCODED |", "|---|---|---|---|",
          f"| Private training: MAPPO and DQN-SA pooled, DQN-I local, rules no model | A table, C row | training design stated in the paper (Sec. 4 and the controller table): MAPPO's critic reads every gNB's features, DQN-SA learns over the joint state, DQN-I trains each gNB on its own requests | BY DESIGN, not measured |",
          f"| DQN-SA and DQN-I cannot run at another size | A, B, C, D | input dimension fixed by the number of gNBs; params rows show the growth | BY DESIGN |",
          f"| Tuned rule transfers 7 to 19 gNBs in Env B | A table | the rule tuned at 7 gNBs hex ({R}m64/n7_hex/rule_local_selection.json) run unchanged at 19 ({R}m75/D_envB_n19_hex/rule_local_transfer); the old script types the label \"7 to 19\" ({OLD}, matrix()) | HARDCODED label, traceable source |",
          f"| Static rule is size-free | A table, C row | one threshold, tau 0, chosen in Env A on training streams; its 37-gNB compliance is measured | label only |",
          "| Learns its rules (yes for learners, no for rules) | not used; dropped in C as asked, absent from A, B, D | typed in the old script's matrix() | HARDCODED in old script |"]
    L += ["", "## Values on the current Fig. 10 and where each variant takes them", "",
          "| Current figure | Value | Recomputed here |", "|---|---|---|",
          f"| AXIOM compliance at 37 | 93.7% | sla37 AXIOM {D['sla37']['axiom2']['mean']:.2f} |",
          f"| AXIOM after 7 to 37 | 95-96% | transfer37 by layout {', '.join(f'{x:.2f}' for x in D['transfer37']['axiom2']['by_layout'].values())} |",
          f"| MAPPO after 7 to 37 | 61.5% | {D['transfer37']['mappo_tuned']['by_layout']['hex']:.2f} (hex), pooled {D['transfer37']['mappo_tuned']['mean']:.2f} |",
          f"| +8.7 reward per step | over the carried tuned rule at 120% | {max(v['diff'] for v in D['over_tuned_rule_m76'].values()):.2f} |",
          f"| 27-36% over MAPPO | Env B 3 and 19 gNBs | {D['over_mappo_pct']['3']['pct']:.2f} and {D['over_mappo_pct']['19']['pct']:.2f} |",
          f"| 7-44x shorter delay | learned / AXIOM | {min(D['delay_ratio'].values()):.2f} to {max(D['delay_ratio'].values()):.2f} |",
          f"| 35.0 points | lead at 37 | {D['lead37']['points']:.2f} |"]
    open(os.path.join(HERE, "DATA_MANIFEST.md"), "w").write("\n".join(L) + "\n")
    print("DATA_MANIFEST.md written,", len(L), "lines")


if __name__ == "__main__":
    main()
